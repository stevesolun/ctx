def test_hf_card_sync_checks_repo_stats_before_export(
    monkeypatch: Any,
    tmp_path: Path,
) -> None:
    calls: list[str] = []

    class FakeApi:
        def __init__(self, *, token: str) -> None:
            calls.append(f"api:{token}")

    fake_hub = type(sys)("huggingface_hub")
    setattr(fake_hub, "HfApi", FakeApi)
    monkeypatch.setitem(sys.modules, "huggingface_hub", fake_hub)
    monkeypatch.setattr(
        sync_huggingface,
        "_git",
        lambda _repo, *_args: "abcdef1234567890",
    )
    monkeypatch.setattr(
        sync_huggingface,
        "_assert_repo_stats_current",
        lambda _repo: calls.append("stats"),
    )

    def fake_export(_repo: Path, _export_dir: Path) -> None:
        calls.append("export")

    monkeypatch.setattr(sync_huggingface, "_export_card_inputs", fake_export)
    monkeypatch.setattr(
        sync_huggingface,
        "_ensure_hf_repo_exists",
        lambda **_kwargs: calls.append("ensure"),
    )

    def fake_upload(**_kwargs: Any) -> str:
        calls.append("upload")
        return "https://example.test/commit"

    monkeypatch.setattr(
        sync_huggingface,
        "_upload_card_inputs",
        fake_upload,
    )

    url = sync_huggingface.sync_card_to_huggingface(
        repo=tmp_path,
        repo_id="Stevesolun/ctx",
        repo_type="dataset",
        token="hf-token",
    )

    assert url == "https://example.test/commit"
    assert calls == ["stats", "export", "api:hf-token", "ensure", "upload"]


def test_mcp_env_placeholders_do_not_expand_credentials_into_argv_by_default(
    monkeypatch: Any,
) -> None:
    from ctx.adapters.generic.tools import McpServerConfig, mcp_router

    monkeypatch.setenv("MCP_API_KEY", "argv-only-secret")
    cfg = McpServerConfig(
        name="argvserver",
        command="server",
        args=("--api-key", "${MCP_API_KEY}", "--header=Bearer $MCP_API_KEY"),
        credential_env=("MCP_API_KEY",),
    )

    env = mcp_router._child_env_for_config(cfg)

    with pytest.raises(ValueError, match="sensitive env var 'MCP_API_KEY'"):
        mcp_router._expand_config_args(cfg, env)
    assert cfg.args[1] == "${MCP_API_KEY}"
