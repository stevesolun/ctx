def test_preflight_refuses_oversized_graph_lfs_pointer_before_pull(
    monkeypatch: Any,
    tmp_path: Path,
    capsys: Any,
) -> None:
    monkeypatch.setattr(ci_preflight, "REPO_ROOT", tmp_path)
    artifact = tmp_path / "graph" / "wiki-graph.tar.gz"
    artifact.parent.mkdir()
    max_size = ci_preflight.GRAPH_LFS_MAX_FALLBACK_SIZES["graph/wiki-graph.tar.gz"]
    artifact.write_text(
        f"version https://git-lfs.github.com/spec/v1\noid sha256:{'a' * 64}\nsize {max_size + 1}\n",
        encoding="utf-8",
    )
    monkeypatch.setattr(ci_preflight.shutil, "which", lambda _name: "/usr/bin/git")

    def fail_run(*_args: Any, **_kwargs: Any) -> None:
        raise AssertionError("git lfs pull should not run")

    monkeypatch.setattr(ci_preflight.subprocess, "run", fail_run)

    assert ci_preflight.hydrate_graph_lfs_artifacts() == 1
    assert "exceeds cap" in capsys.readouterr().err


def test_hf_card_export_uploads_docs_and_changelog(
    monkeypatch: Any,
    tmp_path: Path,
) -> None:
    repo = tmp_path / "repo"
    export_dir = tmp_path / "export"
    (repo / "docs").mkdir(parents=True)
    export_dir.mkdir()
    (repo / "README.md").write_text("# ctx\n", encoding="utf-8")
    (repo / "CHANGELOG.md").write_text("# Changelog\n", encoding="utf-8")
    (repo / "docs" / "guide.md").write_text("# Guide\n", encoding="utf-8")
    monkeypatch.setattr(
        sync_huggingface,
        "_iter_tracked_files",
        lambda _repo: [
            Path("README.md"),
            Path("CHANGELOG.md"),
            Path("docs/guide.md"),
            Path("src/not-card.py"),
        ],
    )

    sync_huggingface._export_card_inputs(repo, export_dir)

    assert (export_dir / "README.md").read_text(encoding="utf-8").startswith("---\nlicense: mit\n")
    assert (export_dir / "CHANGELOG.md").read_text(encoding="utf-8") == "# Changelog\n"
    assert (export_dir / "docs" / "guide.md").read_text(encoding="utf-8") == "# Guide\n"
    assert not (export_dir / "src").exists()

    api = _FakeHfApi()
    url = sync_huggingface._upload_card_inputs(
        api=api,
        export_dir=export_dir,
        repo_id="Stevesolun/ctx",
        repo_type="dataset",
        head="abcdef1234567890",
    )

    assert url == "https://huggingface.co/datasets/Stevesolun/ctx/commit/card"
    assert api.calls == [
        (
            "upload_folder",
            {
                "repo_id": "Stevesolun/ctx",
                "repo_type": "dataset",
                "folder_path": str(export_dir),
                "commit_message": "Sync ctx card abcdef1",
                "commit_description": "GitHub commit: abcdef1234567890",
                "delete_patterns": list(sync_huggingface.CARD_ONLY_DELETE_PATTERNS),
            },
        )
    ]


